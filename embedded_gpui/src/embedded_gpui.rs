//! GPUI running inside a Wasm component, embedded back into a native GPUI application.
//!
//! One crate serves both sides of the boundary:
//!
//! - the **object layer** (this file, always compiled): [`Remote`], [`Receipt`],
//!   [`Ref`], [`Payload`], interfaces/messages/events, and the [`Shared`] home trait —
//!   the typed veneer over the dynamic wire, where everything is
//!   `(target, method: string, payload: bytes + refs)`;
//! - the **object registry** (`registry`, always compiled): one side-blind
//!   implementation of homes and projections that both ends run identically, configured
//!   only with a transport;
//! - the **well-known UI schemas** ([`surface`], always compiled): a host-homed
//!   [`SurfaceApi`] (a place pixels go) and a guest-homed [`ViewApi`] (the thing drawing
//!   there), which is all the protocol knows about views;
//! - the **host runtime** ([`PluginHost`] and friends; native targets only): wasmtime
//!   glue, the [`Surface`] entity that replays display lists, and the transport;
//! - the **guest platform** (wasm32 targets only): a GPUI `Platform` implementation over
//!   the WIT protocol, plus [`Plugin`], [`register_plugin!`], [`open_view`], and the
//!   guest-side transport (`share`, `share_root`, `root`, and friends).
//!
//! See `DESIGN.md` at the repository root for the architecture.

