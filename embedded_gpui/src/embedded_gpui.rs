/// A message that can be sent to a shared object's home end.
pub trait Message: Serialize + DeserializeOwned + 'static {
    /// The entity kind this message addresses.
    type Spec: Interface;

    /// The value the home's handler returns. `()` for fire-and-forget casts.
    type Response: Serialize + DeserializeOwned + 'static;

    /// Stable method name used for dynamic dispatch on the home side.
    const METHOD: &'static str;
}

/// An event flowing from a shared object's home to every remote on the other end: the
/// boundary-crossing form of GPUI's `cx.emit`. Declared in a schema via the `events`
/// list of [`interface`]; received with [`Remote::subscribe`].
pub trait Event: Serialize + DeserializeOwned + 'static {
    /// The entity kind this event belongs to.
    type Spec: Interface;

    /// Stable event name used for dynamic dispatch on the remote side.
    const EVENT: &'static str;
}

/// Encoded message content: the serialized bytes plus the table of every [`Ref`] they
/// mention. Bytes name refs by index into `refs`, so a forwarder can rewrite which
/// objects a payload points at without parsing it, and the registry can account for
/// every capability in transit.
///
/// Payloads arriving from the other end are bound to the registry that delivered them
/// ([`Payload::registry`]), which is what lets a decoded `Ref` know where to connect.
#[derive(Clone, Default)]
pub struct Payload {
    pub bytes: Vec<u8>,
    pub refs: Vec<u64>,
    registry: Option<registry::WeakObjects>,
}

impl Payload {
    /// Wire content with no ref table (unit responses, control frames).
    pub fn empty() -> Self {
        Self::default()
    }

    /// Wire content with an explicit ref table, as a forwarder rebuilds it.
    pub fn from_parts(bytes: Vec<u8>, refs: Vec<u64>) -> Self {
        Self {
            bytes,
            refs,
            registry: None,
        }
    }

    /// The registry this payload arrived through, if it arrived at all.
    pub fn registry(&self) -> Option<Registry> {
        self.registry.clone().map(Registry)
    }

    pub(crate) fn bound(mut self, registry: registry::WeakObjects) -> Self {
        self.registry = Some(registry);
        self
    }
}

impl std::fmt::Debug for Payload {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter
            .debug_struct("Payload")
            .field("bytes", &self.bytes.len())
            .field("refs", &self.refs)
            .finish()
    }
}

thread_local! {
    /// The ref table of the payload currently being encoded or decoded. Serde gives
    /// `Ref`'s (de)serializers no other channel to the enclosing payload.
    static REF_TABLE: RefCell<Option<RefTable>> = const { RefCell::new(None) };
}

struct RefTable {
    refs: Vec<u64>,
    registry: Option<registry::WeakObjects>,
}

fn with_ref_table<R>(table: RefTable, f: impl FnOnce() -> R) -> (R, RefTable) {
    let previous = REF_TABLE.with(|slot| slot.borrow_mut().replace(table));
    let result = f();
    let table = REF_TABLE.with(|slot| {
        let table = slot
            .borrow_mut()
            .take()
            .expect("ref table taken mid-encoding");
        *slot.borrow_mut() = previous;
        table
    });
    (result, table)
}

/// Serialize a value into a [`Payload`], collecting every [`Ref`] it mentions into the
/// ref table.
pub fn encode<T: Serialize>(value: &T) -> anyhow::Result<Payload> {
    let (bytes, table) = with_ref_table(
        RefTable {
            refs: Vec::new(),
            registry: None,
        },
        || serde_json::to_vec(value),
    );
    Ok(Payload {
        bytes: bytes?,
        refs: table.refs,
        registry: None,
    })
}

/// Deserialize a [`Payload`]; every [`Ref`] inside is bound to the registry the payload
/// arrived through, so it can be connected wherever it ends up.
pub fn decode<T: DeserializeOwned>(payload: &Payload) -> anyhow::Result<T> {
    let (value, _) = with_ref_table(
        RefTable {
            refs: payload.refs.clone(),
            registry: payload.registry.clone(),
        },
        || serde_json::from_slice(&payload.bytes),
    );
    Ok(value?)
}

/// What a method handler produced: an immediate response, or asynchronous work whose
/// result becomes the response when it resolves. Async handlers are what make caretakers
/// possible: a handler can await calls on other refs and pipe their responses through.
pub enum HandlerResponse {
    Ready(anyhow::Result<Payload>),
    Pending(gpui::Task<anyhow::Result<Payload>>),
}

/// A type-erased method handler on an entity's home side: decode, dispatch, encode the
/// response. Receives the method name so wildcard handlers can interpret it. Used
/// identically by the native host and the wasm guest.
pub type MethodHandler = Rc<dyn Fn(&str, &Payload, &mut gpui::App) -> HandlerResponse>;

/// Registering a handler under this name makes it the fallback for any method that has
/// no explicit entry: fully dynamic dispatch, decided by the entity at runtime. Purely a
/// [`Methods`] convention — the registry stores exactly one handler per object and never
/// interprets method names itself.
pub const WILDCARD_METHOD: &str = "*";

/// A dispatch table under construction: the dynamic escape hatch beneath the typed
/// [`Shared`] registration. Entities that interpret method names at runtime (or
/// wrappers that forward them wholesale via [`WILDCARD_METHOD`]) register here.
///
/// This is userspace: the table compiles down to the single dispatch closure the
/// registry actually stores, so name-keyed dispatch is one library convention among
/// possible ones, not a protocol feature.
pub struct Methods<S: Interface, T> {
    entity: gpui::WeakEntity<T>,
    map: std::collections::HashMap<String, MethodHandler>,
    _spec: PhantomData<S>,
}

impl<S: Interface, T: 'static> Methods<S, T> {
    #[doc(hidden)]
    pub fn new(entity: gpui::WeakEntity<T>) -> Self {
        Self {
            entity,
            map: std::collections::HashMap::new(),
            _spec: PhantomData,
        }
    }

    /// Register a handler for a method name, or for [`WILDCARD_METHOD`] to receive every
    /// method without an explicit entry.
    pub fn on(
        &mut self,
        method: impl Into<String>,
        handler: impl Fn(&gpui::Entity<T>, &str, &Payload, &mut gpui::App) -> anyhow::Result<Payload>
        + 'static,
    ) -> &mut Self {
        let entity = self.entity.clone();
        self.map.insert(
            method.into(),
            Rc::new(move |method, payload, cx| {
                HandlerResponse::Ready((|| {
                    let entity = entity
                        .upgrade()
                        .ok_or_else(|| anyhow::anyhow!("entity dropped"))?;
                    handler(&entity, method, payload, cx)
                })())
            }),
        );
        self
    }

    /// Register an asynchronous handler: it returns a task whose value becomes the
    /// response when it resolves, so the entity can await calls on other refs in between
    /// (forwarding, aggregation, caretakers).
    pub fn on_async(
        &mut self,
        method: impl Into<String>,
        handler: impl Fn(
            &gpui::Entity<T>,
            &str,
            &Payload,
            &mut gpui::App,
        ) -> gpui::Task<anyhow::Result<Payload>>
        + 'static,
    ) -> &mut Self {
        let entity = self.entity.clone();
        self.map.insert(
            method.into(),
            Rc::new(move |method, payload, cx| match entity.upgrade() {
                Some(entity) => HandlerResponse::Pending(handler(&entity, method, payload, cx)),
                None => HandlerResponse::Ready(Err(anyhow::anyhow!("entity dropped"))),
            }),
        );
        self
    }

    #[doc(hidden)]
    /// Compile the table into the one handler the registry stores: look the method up
    /// by name, fall back to the wildcard entry, or fail with a "no method" error.
    pub fn into_handler(self) -> MethodHandler {
        let map = self.map;
        Rc::new(move |method, payload, cx| {
            let Some(handler) = map.get(method).or_else(|| map.get(WILDCARD_METHOD)) else {
                return HandlerResponse::Ready(Err(anyhow::anyhow!(
                    "{} has no method {method:?}",
                    interface_name::<S>()
                )));
            };
            handler(method, payload, cx)
        })
    }
}

/// Forwards a home entity's typed events onto the wire; handed to
/// [`Shared::events`] by the share machinery.
pub type EventSink = Rc<dyn Fn(&str, Payload, &mut gpui::App)>;

/// An entity type that can be shared as an `S`: it knows how to register its method
/// handlers and how to wire its GPUI events to the boundary. Implemented by putting
/// [`macro@shared`] on the interface `impl` block; manual implementations are the
/// escape hatch for fully dynamic entities and generic wrappers.
pub trait Shared<S: Interface>: 'static + Sized {
    /// Install this type's method handlers into the dispatch table.
    fn methods(methods: &mut Methods<S, Self>);

    /// Wire the home entity's typed events to the boundary: subscribe to each event the
    /// schema declares and pipe it through `sink`. `cx.notify` crosses automatically and
    /// is not wired here.
    #[allow(unused_variables)]
    fn events(
        entity: &gpui::Entity<Self>,
        sink: EventSink,
        cx: &mut gpui::App,
    ) -> Vec<gpui::Subscription> {
        Vec::new()
    }

    /// Whether sharing keeps the entity alive until the other end releases it (the
    /// default, like handing out an `Entity<T>`). Entities whose lifetime belongs to
    /// their owner — a [`Surface`](surface::SurfaceApi) lives exactly as long as the
    /// embedder keeps it in its UI — return `false`: remotes to them may dangle, and
    /// calls then fail with "entity dropped".
    fn keep_alive() -> bool {
        true
    }
}

/// The sending half backing a [`Receipt`]: the response payload or an error string.
pub type ResponseSender = futures::channel::oneshot::Sender<Result<Payload, String>>;

fn decode_response<R: DeserializeOwned>(payload: Payload) -> anyhow::Result<R> {
    decode(&payload)
}

fn discard_response(_payload: Payload) -> anyhow::Result<()> {
    Ok(())
}

fn raw_response(payload: Payload) -> anyhow::Result<Payload> {
    Ok(payload)
}

fn missing_response<R>(_payload: Payload) -> anyhow::Result<R> {
    Err(anyhow::anyhow!("object went away before responding"))
}

/// The future returned by every call on a [`Remote`].
///
/// - `Receipt<R>` is a call's response: it resolves with the home handler's return
///   value. Handler errors arrive as `Err`, crossing the boundary as strings. Dropping
///   a receipt is fire-and-forget; the message is unaffected.
/// - `Receipt<Payload>` from [`Remote::call_raw`] resolves with the raw response,
///   undecoded — the forwarding primitive a caretaker pipes straight through; chain
///   [`Receipt::decoded`] or [`Receipt::acknowledged`] to interpret it.
pub struct Receipt<R = ()> {
    receiver: futures::channel::oneshot::Receiver<Result<Payload, String>>,
    decode: Box<dyn Fn(Payload) -> anyhow::Result<R>>,
}

impl Receipt<Payload> {
    #[doc(hidden)]
    pub fn channel() -> (ResponseSender, Self) {
        let (sender, receiver) = futures::channel::oneshot::channel();
        (
            sender,
            Self {
                receiver,
                decode: Box::new(raw_response),
            },
        )
    }

    /// Decode the raw response as `R` when it arrives.
    pub fn decoded<R: DeserializeOwned + 'static>(self) -> Receipt<R> {
        Receipt {
            receiver: self.receiver,
            decode: Box::new(decode_response::<R>),
        }
    }

    /// Keep only the acknowledgement: resolve with `()` once the home has responded.
    pub fn acknowledged(self) -> Receipt {
        Receipt {
            receiver: self.receiver,
            decode: Box::new(discard_response),
        }
    }

    /// Decode the response as a [`Ref`] and connect it, resolving with a live
    /// [`Remote`]: the receipt behind every ref-returning schema method.
    pub fn connected<S: Interface>(self) -> Receipt<Remote<S>> {
        Receipt {
            receiver: self.receiver,
            decode: Box::new(|payload| {
                let reference: Ref<S> = decode(&payload)?;
                Ok(reference.connect())
            }),
        }
    }
}

impl<R: 'static> Receipt<R> {
    /// A receipt that resolves with an error immediately; used when a message could not
    /// be encoded or dispatched at all.
    pub fn dropped() -> Self {
        let (_sender, receiver) = futures::channel::oneshot::channel();
        Self {
            receiver,
            decode: Box::new(missing_response::<R>),
        }
    }
}

impl<R> std::future::Future for Receipt<R> {
    type Output = anyhow::Result<R>;

    fn poll(
        self: std::pin::Pin<&mut Self>,
        cx: &mut std::task::Context<'_>,
    ) -> std::task::Poll<Self::Output> {
        let this = self.get_mut();
        std::pin::Pin::new(&mut this.receiver)
            .poll(cx)
            .map(|result| {
                let outcome =
                    result.map_err(|_| anyhow::anyhow!("object went away before responding"))?;
                let payload = outcome.map_err(|error| anyhow::anyhow!("call failed: {error}"))?;
                (this.decode)(payload)
            })
    }
}

