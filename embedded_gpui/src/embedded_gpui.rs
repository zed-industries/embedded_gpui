/// Identifies an object interface. Generated by [`interface`] as a struct with the
/// same name as the interface, so a handle to a shared counter reads
/// `Remote<CounterApi>`.
pub trait Interface: 'static {
    /// The interface as a runtime value: the same schema the macros compile against,
    /// for reflection (dynamic-language guests, inspectors, generated bindings).
    fn schema() -> Schema;
}

/// The interface's name for diagnostics and the (future) object-graph inspector:
/// `std::any::type_name`, so it costs no codegen and nothing on the wire checks it.
pub(crate) fn interface_name<S: Interface>() -> &'static str {
    std::any::type_name::<S>()
}

