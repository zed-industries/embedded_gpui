/// One end's object registry, as user code holds it: the operations that mint and
/// resolve capabilities, identical on both ends. Every [`Remote`], [`Ref`], and inbound
/// [`Payload`] knows the registry it belongs to ([`Remote::registry`],
/// [`Ref::registry`]), so anything that holds a capability can also share new objects
/// into the same connection — which is what lets a generic forwarder mint wrappers for
/// the refs passing through it.
///
/// The handle is weak: a registry outlived by its handles (the boundary was torn down)
/// makes sharing a no-op that returns refs nobody can reach.
#[derive(Clone)]
pub struct Registry(registry::WeakObjects);

impl Registry {
    pub(crate) fn new(objects: registry::WeakObjects) -> Self {
        Self(objects)
    }

    /// Share a local entity, returning a capability reference to embed in message or
    /// event payloads. The registry holds the entity alive until the other end's last
    /// remote drops (unless the type opts out via [`Shared::keep_alive`]).
    pub fn share<S, T>(&self, entity: &gpui::Entity<T>, cx: &mut gpui::App) -> Ref<S>
    where
        S: Interface,
        T: Shared<S>,
    {
        match self.0.upgrade() {
            Some(objects) => objects.share(entity, cx),
            None => Ref::detached(),
        }
    }

    /// [`Registry::share`] with a closure-registered dispatch table instead of a schema
    /// interface: the dynamic escape hatch. `cx.notify` still crosses; typed events are
    /// not wired (implement [`Shared`] manually if you need both).
    pub fn share_with<S, T>(
        &self,
        entity: &gpui::Entity<T>,
        register: impl FnOnce(&mut Methods<S, T>),
        cx: &mut gpui::App,
    ) -> Ref<S>
    where
        S: Interface,
        T: 'static,
    {
        match self.0.upgrade() {
            Some(objects) => objects.share_with(entity, register, cx),
            None => Ref::detached(),
        }
    }

    /// Attach to the other end's root object (the reserved address 0 means "your root"
    /// from either direction).
    pub fn root<S: Interface>(&self) -> Remote<S> {
        match self.0.upgrade() {
            Some(objects) => objects.root(),
            None => Remote::from_parts(self.0.clone(), 0, None),
        }
    }

    /// Resolve an object id in this registry. Prefer [`Ref::connect`]; this is for
    /// forwarders that hold ids out of a ref table rather than typed refs.
    pub fn connect<S: Interface>(&self, id: u64) -> Remote<S> {
        match self.0.upgrade() {
            Some(objects) => objects.connect_id(id),
            None => Remote::from_parts(self.0.clone(), id, None),
        }
    }

    /// Whether `id` is an object homed on this end.
    pub fn is_local(&self, id: u64) -> bool {
        self.0.upgrade().is_some_and(|objects| objects.is_local(id))
    }
}

/// A typed handle to an entity homed on the other side of the boundary. The nearest
/// thing to `Entity<T>` that can cross a sandbox wall:
///
/// - **call methods** — [`Remote::call`] / [`Remote::call_raw`], or the typed methods
///   a schema's generated `...Caller` trait adds (methods returning refs resolve
///   directly to connected `Remote`s); fire-and-forget is dropping the receipt;
/// - **react to it** — [`Remote::observe`] mirrors the home's `cx.notify`,
///   [`Remote::subscribe`] its typed `cx.emit` events;
/// - **refcounted** — clones share one guard; when the last clone of a ref-derived
///   remote drops, the home is told to let the entity go.
///
/// A remote is its registry handle plus an object id: it holds its registry weakly, so
/// it can outlive the boundary it came from (calls then resolve their receipts with
/// errors).
///
/// Reads are calls: state lives at the home, and anything you want to look at is a
/// method returning it (cache it locally with `embedded_gpui_util::Mirror` if you need
/// synchronous reads for rendering).
pub struct Remote<S: Interface> {
    objects: registry::WeakObjects,
    entity_id: u64,
    _guard: Option<Rc<dyn std::any::Any>>,
    _spec: PhantomData<fn() -> S>,
}

impl<S: Interface> Clone for Remote<S> {
    fn clone(&self) -> Self {
        Self {
            objects: self.objects.clone(),
            entity_id: self.entity_id,
            _guard: self._guard.clone(),
            _spec: PhantomData,
        }
    }
}

impl<S: Interface> std::fmt::Debug for Remote<S> {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            formatter,
            "Remote<{}>({})",
            interface_name::<S>(),
            self.entity_id
        )
    }
}

impl<S: Interface> Remote<S> {
    pub(crate) fn from_parts(
        objects: registry::WeakObjects,
        entity_id: u64,
        guard: Option<Rc<dyn std::any::Any>>,
    ) -> Self {
        Self {
            objects,
            entity_id,
            _guard: guard,
            _spec: PhantomData,
        }
    }

    /// The registry this remote belongs to.
    pub fn registry(&self) -> Registry {
        Registry(self.objects.clone())
    }

    /// Mint the serializable capability reference for this entity, for embedding in
    /// message or event payloads.
    pub fn reference(&self) -> Ref<S> {
        Ref::new(self.entity_id, self.objects.clone())
    }

    fn request(&self, method: &str, payload: Payload) -> Receipt<Payload> {
        let (sender, receipt) = Receipt::channel();
        match self.objects.upgrade() {
            // Dropping `sender` resolves the receipt with an error.
            None => log::warn!("embedded_gpui: call after the boundary was torn down"),
            Some(objects) => objects.send(self.entity_id, method, payload, Some(sender)),
        }
        receipt
    }

    /// The signal this remote's events land on, created on first use; a detached,
    /// never-firing stand-in if the boundary or projection is gone.
    fn signal(&self, cx: &mut gpui::App) -> gpui::Entity<RemoteSignal> {
        self.objects
            .upgrade()
            .and_then(|objects| objects.signal_for(self.entity_id, cx))
            .unwrap_or_else(|| cx.new(|_| RemoteSignal::new()))
    }

    /// Call a typed method on the entity's home, resolving with its return value.
    /// Await the receipt for the value (or the error), or drop it for fire-and-forget;
    /// the message is applied either way.
    pub fn call<M: Message<Spec = S>>(
        &self,
        message: M,
        _cx: &mut gpui::App,
    ) -> Receipt<M::Response> {
        match encode(&message) {
            Ok(payload) => self.request(M::METHOD, payload).decoded(),
            Err(error) => {
                log::error!(
                    "embedded_gpui: failed to encode {}::{}: {error:#}",
                    interface_name::<S>(),
                    M::METHOD
                );
                Receipt::dropped()
            }
        }
    }

    /// Call a typed method whose return value is a capability reference, resolving
    /// with a live [`Remote`] already connected to it: object allocation across the
    /// boundary, one call from handle to handle. The schema's generated caller uses
    /// this for every `Ref`-returning method.
    pub fn call_connecting<M, S2>(&self, message: M, _cx: &mut gpui::App) -> Receipt<Remote<S2>>
    where
        M: Message<Spec = S, Response = Ref<S2>>,
        S2: Interface,
    {
        match encode(&message) {
            Ok(payload) => self.request(M::METHOD, payload).connected(),
            Err(error) => {
                log::error!(
                    "embedded_gpui: failed to encode {}::{}: {error:#}",
                    interface_name::<S>(),
                    M::METHOD
                );
                Receipt::dropped()
            }
        }
    }

    /// The dynamic escape hatch: call a method by name with a pre-encoded payload,
    /// resolving with the raw response. This is the forwarding primitive — a caretaker
    /// pipes these straight through — and the base of the typed verbs: chain
    /// [`Receipt::decoded`] for a typed value or [`Receipt::acknowledged`] for a bare
    /// ack.
    pub fn call_raw(
        &self,
        method: &str,
        payload: Payload,
        _cx: &mut gpui::App,
    ) -> Receipt<Payload> {
        self.request(method, payload)
    }

    /// React to the home entity's `cx.notify`, exactly like `cx.observe` on a local
    /// entity. The home notifies once on subscription, so observers always fire at least
    /// once after attaching.
    pub fn observe(
        &self,
        cx: &mut gpui::App,
        mut callback: impl FnMut(&mut gpui::App) + 'static,
    ) -> gpui::Subscription {
        let signal = self.signal(cx);
        cx.observe(&signal, move |_, cx| callback(cx))
    }

    /// React to a typed event the home emitted with `cx.emit`, exactly like
    /// `cx.subscribe` on a local entity.
    pub fn subscribe<E: Event<Spec = S>>(
        &self,
        cx: &mut gpui::App,
        mut callback: impl FnMut(&E, &mut gpui::App) + 'static,
    ) -> gpui::Subscription {
        let signal = self.signal(cx);
        cx.subscribe(&signal, move |_, event: &RawEvent, cx| {
            if event.name == E::EVENT {
                match decode::<E>(&event.payload) {
                    Ok(event) => callback(&event, cx),
                    Err(error) => log::error!(
                        "embedded_gpui: failed to decode {} event {:?}: {error:#}",
                        interface_name::<S>(),
                        E::EVENT
                    ),
                }
            }
        })
    }

    /// React to every event from the home, undecoded: the forwarding primitive for
    /// events, mirroring [`Remote::call_raw`] for calls.
    pub fn subscribe_raw(
        &self,
        cx: &mut gpui::App,
        mut callback: impl FnMut(&str, &Payload, &mut gpui::App) + 'static,
    ) -> gpui::Subscription {
        let signal = self.signal(cx);
        cx.subscribe(&signal, move |_, event: &RawEvent, cx| {
            callback(&event.name, &event.payload, cx)
        })
    }
}

/// A serializable capability reference to a shared entity of kind `S`: how objects
/// travel. An entity lives on one end; a [`Remote`] is how the other end holds it; a
/// `Ref` is how it moves through payloads (including call responses and events).
///
/// On the wire this is `{"$ref": index}` into the payload's ref table, which holds the
/// entity id — random, so possession is the authority: a ref can be known but never
/// guessed. The `$ref` shape makes refs findable in a payload without its schema, which
/// is what a dynamic-language guest needs. A ref also remembers the registry it was
/// minted by or arrived through, so [`Ref::connect`] turns it back into a live handle
/// from anywhere (schema methods declared to return a `Ref` do this on arrival,
/// resolving with a connected `Remote`).
pub struct Ref<S: Interface> {
    entity_id: u64,
    objects: registry::WeakObjects,
    _spec: PhantomData<fn() -> S>,
}

impl<S: Interface> Ref<S> {
    pub(crate) fn new(entity_id: u64, objects: registry::WeakObjects) -> Self {
        Self {
            entity_id,
            objects,
            _spec: PhantomData,
        }
    }

    /// A ref bound to no registry: connecting it yields a remote whose calls all fail.
    fn detached() -> Self {
        Self::new(0, registry::WeakObjects::detached())
    }

    pub fn entity_id(&self) -> u64 {
        self.entity_id
    }

    /// The registry this ref belongs to.
    pub fn registry(&self) -> Registry {
        Registry(self.objects.clone())
    }

    /// Attach to the entity: the same projection for the same ref, refcounted across
    /// clones; when the last clone drops, the home end is told to release the entity.
    pub fn connect(&self) -> Remote<S> {
        Registry(self.objects.clone()).connect(self.entity_id)
    }
}

impl<S: Interface> Clone for Ref<S> {
    fn clone(&self) -> Self {
        Self::new(self.entity_id, self.objects.clone())
    }
}

impl<S: Interface> std::fmt::Debug for Ref<S> {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            formatter,
            "Ref<{}>({})",
            interface_name::<S>(),
            self.entity_id
        )
    }
}

impl<S: Interface> PartialEq for Ref<S> {
    fn eq(&self, other: &Self) -> bool {
        self.entity_id == other.entity_id
    }
}

impl<S: Interface> Eq for Ref<S> {}

impl<S: Interface> Serialize for Ref<S> {
    fn serialize<Ser: serde::Serializer>(&self, serializer: Ser) -> Result<Ser::Ok, Ser::Error> {
        let index = REF_TABLE.with(|slot| {
            let mut slot = slot.borrow_mut();
            let table = slot.as_mut()?;
            let index = table.refs.len();
            table.refs.push(self.entity_id);
            Some(index as u64)
        });
        match index {
            Some(index) => RefWire { index }.serialize(serializer),
            None => Err(serde::ser::Error::custom(
                "a Ref can only be serialized inside embedded_gpui::encode",
            )),
        }
    }
}

/// The JSON shape of a ref: `{"$ref": index}`.
#[derive(Serialize, serde::Deserialize)]
struct RefWire {
    #[serde(rename = "$ref")]
    index: u64,
}

impl<'de, S: Interface> serde::Deserialize<'de> for Ref<S> {
    fn deserialize<De: serde::Deserializer<'de>>(deserializer: De) -> Result<Self, De::Error> {
        let index = RefWire::deserialize(deserializer)?.index as usize;
        let resolved = REF_TABLE.with(|slot| {
            let slot = slot.borrow();
            let table = slot.as_ref()?;
            let entity_id = *table.refs.get(index)?;
            Some((entity_id, table.registry.clone()))
        });
        match resolved {
            Some((entity_id, Some(registry))) => Ok(Self::new(entity_id, registry)),
            Some((_, None)) => Err(serde::de::Error::custom(
                "a Ref can only be decoded from a payload that arrived through a registry",
            )),
            None => Err(serde::de::Error::custom(format!(
                "ref index {index} is not in the payload's ref table"
            ))),
        }
    }
}
